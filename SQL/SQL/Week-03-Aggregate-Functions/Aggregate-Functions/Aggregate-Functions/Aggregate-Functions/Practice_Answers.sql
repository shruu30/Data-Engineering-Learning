

/******************************************************************************************
 Question 1
 Display the total number of employees.
******************************************************************************************/

SELECT COUNT(*) AS TotalEmployees
FROM Employee;

--------------------------------------------------------------------------------------------

/******************************************************************************************
 Question 2
 Display the total salary of all employees.
******************************************************************************************/

SELECT SUM(Salary) AS TotalSalary
FROM Employee;

--------------------------------------------------------------------------------------------

/******************************************************************************************
 Question 3
 Display the average salary of employees.
******************************************************************************************/

SELECT AVG(Salary) AS AverageSalary
FROM Employee;

--------------------------------------------------------------------------------------------

/******************************************************************************************
 Question 4
 Display the highest and lowest salary.
******************************************************************************************/

SELECT
    MAX(Salary) AS HighestSalary,
    MIN(Salary) AS LowestSalary
FROM Employee;

--------------------------------------------------------------------------------------------

/******************************************************************************************
 Question 5
 Display the number of employees in each department.
******************************************************************************************/

SELECT
    DepartmentID,
    COUNT(*) AS TotalEmployees
FROM Employee
GROUP BY DepartmentID;

--------------------------------------------------------------------------------------------

/******************************************************************************************
 Question 6
 Display the total salary paid by each department.
******************************************************************************************/

SELECT
    DepartmentID,
    SUM(Salary) AS TotalSalary
FROM Employee
GROUP BY DepartmentID;

--------------------------------------------------------------------------------------------

/******************************************************************************************
 Question 7
 Display departments where more than one employee works.
******************************************************************************************/

SELECT
    DepartmentID,
    COUNT(*) AS TotalEmployees
FROM Employee
GROUP BY DepartmentID
HAVING COUNT(*) > 1;

--------------------------------------------------------------------------------------------

/******************************************************************************************
 Question 8
 Display employees with Salary Category.
******************************************************************************************/

SELECT
    EmployeeName,
    Salary,
    CASE
        WHEN Salary >= 70000 THEN 'High'
        WHEN Salary >= 50000 THEN 'Medium'
        ELSE 'Low'
    END AS SalaryCategory
FROM Employee;

--------------------------------------------------------------------------------------------

/******************************************************************************************
 Question 9
 Display the average salary for each city.
******************************************************************************************/

SELECT
    City,
    AVG(Salary) AS AverageSalary
FROM Employee
GROUP BY City;

--------------------------------------------------------------------------------------------

/******************************************************************************************
 Question 10
 Display departments whose average salary is greater than 60000.
******************************************************************************************/

SELECT
    DepartmentID,
    AVG(Salary) AS AverageSalary
FROM Employee
GROUP BY DepartmentID
HAVING AVG(Salary) > 60000;


